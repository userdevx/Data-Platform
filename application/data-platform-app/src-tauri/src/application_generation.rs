use serde::Serialize;
use std::fs;
use std::path::{Path, PathBuf};
use std::time::{SystemTime, UNIX_EPOCH};

#[derive(Debug, Serialize)]
pub struct GeneratedApplication {
    pub success: bool,
    pub project_name: String,
    pub project_path: String,
    pub application_type: String,
    pub files: Vec<String>,
    pub message: String,
}

#[derive(Debug, Serialize)]
struct ApplicationSpec<'a> {
    name: &'a str,
    application_type: &'a str,
    request: &'a str,
    generator: &'a str,
}

fn slugify(value: &str) -> String {
    let mut output = String::new();
    let mut previous_dash = false;

    for character in value.chars() {
        if character.is_ascii_alphanumeric() {
            output.push(character.to_ascii_lowercase());

            previous_dash = false;
        } else if !previous_dash && !output.is_empty() {
            output.push('-');
            previous_dash = true;
        }

        if output.len() >= 48 {
            break;
        }
    }

    while output.ends_with('-') {
        output.pop();
    }

    if output.is_empty() {
        "generated-application".to_string()
    } else {
        output
    }
}

fn project_name_from_request(request: &str) -> String {
    let words = request
        .split_whitespace()
        .take(6)
        .collect::<Vec<_>>()
        .join(" ");

    slugify(&words)
}

fn write_file(project_root: &Path, relative_path: &str, content: &str) -> Result<(), String> {
    let path = project_root.join(relative_path);

    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent)
            .map_err(|error| format!("Could not create {}: {}", parent.display(), error,))?;
    }

    fs::write(&path, content)
        .map_err(|error| format!("Could not write {}: {}", path.display(), error,))
}

fn html_escape(value: &str) -> String {
    value
        .replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('"', "&quot;")
}

fn json_string(value: &str) -> Result<String, String> {
    serde_json::to_string(value)
        .map_err(|error| format!("Could not encode generated application text: {}", error,))
}

