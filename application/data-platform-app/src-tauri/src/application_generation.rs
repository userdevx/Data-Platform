fn data_application_files(
    project_name: &str,
    request: &str,
) -> Result<Vec<(String, String)>, String> {
    const TEMPLATE: &str = r##"#!/usr/bin/env python3

import argparse
import csv
from pathlib import Path


APP_NAME = __APP_NAME__
REQUEST = __REQUEST__


def inspect_csv(
    path: Path,
) -> None:
    with path.open(
        "r",
        encoding="utf-8",
        newline="",
    ) as handle:
        reader = csv.reader(
            handle,
        )

        try:
            header = next(
                reader,
            )
        except StopIteration:
            print(
                "CSV file is empty.",
            )
            return

        row_count = sum(
            1
            for _ in reader
        )

    print(APP_NAME)
    print(REQUEST)
    print()
    print(
        "File:",
        path,
    )
    print(
        "Rows:",
        row_count,
    )
    print(
        "Columns:",
        len(header),
    )
    print(
        "Column names:",
    )

    for column in header:
        print(
            " -",
            column,
        )


def main() -> None:
    parser = argparse.ArgumentParser(
        description=APP_NAME,
    )

    parser.add_argument(
        "csv_file",
        type=Path,
    )

    args = parser.parse_args()

    inspect_csv(
        args.csv_file,
    )


if __name__ == "__main__":
    main()
"##;

    let content = TEMPLATE
        .replace("__APP_NAME__", &json_string(project_name)?)
        .replace("__REQUEST__", &json_string(request)?);

    Ok(vec![("src/main.py".to_string(), content)])
}

fn automation_tool_files(
    project_name: &str,
    request: &str,
) -> Result<Vec<(String, String)>, String> {
    const TEMPLATE: &str = r##"#!/usr/bin/env python3

import argparse
from datetime import datetime


APP_NAME = __APP_NAME__
REQUEST = __REQUEST__


def run_task(
    value: str,
) -> None:
    timestamp = datetime.now().isoformat(
        timespec="seconds",
    )

    print(
        "[",
        timestamp,
        "] ",
        APP_NAME,
        sep="",
    )

    print(
        "Request:",
        REQUEST,
    )

    print(
        "Input:",
        value,
    )

    print(
        "Automation completed.",
    )


def main() -> None:
    parser = argparse.ArgumentParser(
        description=APP_NAME,
    )

    parser.add_argument(
        "--input",
        default="default",
    )

    args = parser.parse_args()

    run_task(
        args.input,
    )


if __name__ == "__main__":
    main()
"##;

    let content = TEMPLATE
        .replace("__APP_NAME__", &json_string(project_name)?)
        .replace("__REQUEST__", &json_string(request)?);

    Ok(vec![("src/main.py".to_string(), content)])
}

fn generated_files(
    application_type: &str,
    project_name: &str,
    request: &str,
) -> Result<Vec<(String, String)>, String> {
    match application_type {
        "Web application" => Ok(web_application_files(project_name, request)),

        "Desktop application" => desktop_application_files(project_name, request),

        "Data application" => data_application_files(project_name, request),

        "Automation tool" => automation_tool_files(project_name, request),

        _ => Err(format!(
            "Unsupported application type: {}",
            application_type,
        )),
    }
}

#[tauri::command]
pub fn generate_application_scaffold(
    request: String,
    application_type: String,
) -> Result<GeneratedApplication, String> {
    let clean_request = request.trim();

    if clean_request.is_empty() {
        return Err("Describe the application before building.".to_string());
    }

    let project_name = project_name_from_request(clean_request);

    let timestamp = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map_err(|error| format!("Could not determine build timestamp: {}", error,))?
        .as_secs();

    let application_root = crate::intelligence_bridge::get_application_root()?;

    let output_root = PathBuf::from(application_root)
        .join("output")
        .join("generated-applications");

    fs::create_dir_all(&output_root)
        .map_err(|error| format!("Could not create {}: {}", output_root.display(), error,))?;

    let directory_name = format!("{}-{}", project_name, timestamp,);

    let project_root = output_root.join(directory_name);

    fs::create_dir_all(&project_root).map_err(|error| {
        format!(
            "Could not create project {}: {}",
            project_root.display(),
            error,
        )
    })?;

    let specification = ApplicationSpec {
        name: &project_name,

        application_type: &application_type,

        request: clean_request,

        generator: "dataworc.application_generation.v1",
    };

    let specification_json = serde_json::to_string_pretty(&specification)
        .map_err(|error| format!("Could not serialize application specification: {}", error,))?;

    write_file(&project_root, "application.json", &specification_json)?;

    let mut files = vec!["application.json".to_string()];

    let generated = generated_files(&application_type, &project_name, clean_request)?;

    for (relative_path, content) in generated {
        write_file(&project_root, &relative_path, &content)?;

        files.push(relative_path);
    }

    let readme = format!(
        "# {}\n\n\
             Generated by DataWorc Application Generation.\n\n\
             ## Type\n\n{}\n\n\
             ## Request\n\n{}\n\n\
             ## Status\n\n\
             This is the first real Application Generation vertical slice.\n\
             Local-model refinement and sandbox compile/test are the next stage.\n",
        project_name, application_type, clean_request,
    );

    write_file(&project_root, "README.md", &readme)?;

    files.push("README.md".to_string());

    Ok(GeneratedApplication {
        success: true,

        project_name: project_name.clone(),

        project_path: project_root.to_string_lossy().into_owned(),

        application_type,

        files,

        message: format!("Generated {} successfully.", project_name,),
    })
}
